#String are sequences of characters which are immutable
#String can be created using single or double quotes
print("Hello world")#Using double quotes
print('Hello world')#Using single quotes
print("Hello 'World'")#Using double quotes with single quotes inside
print('Hello "World"')#Using single quotes with double quotes inside
#String can be created using triple quotes for multi-line strings
print("""This is Sohail
      Ahmad Khan
      Ahmad Khan
      Ahmad Khan""")